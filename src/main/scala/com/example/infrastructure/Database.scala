package com.example.infrastructure

import java.sql.{Connection, DriverManager}

import scala.util.Using

import com.zaxxer.hikari.HikariDataSource
import org.h2.jdbcx.JdbcDataSource

object Database:
  def url(path: String): String =
    s"jdbc:h2:file:$path;DB_CLOSE_DELAY=-1"

  def memoryUrl(name: String): String =
    s"jdbc:h2:mem:$name;DB_CLOSE_DELAY=-1"

  def ensureDriver(): Unit =
    try Class.forName("org.h2.Driver")
    catch case _: ClassNotFoundException =>
      throw new IllegalStateException("H2 JDBC driver is not on the classpath")

  def open(url: String, user: String = DatabaseConfig.DefaultUser, password: String = DatabaseConfig.DefaultPassword): Database =
    ensureDriver()
    Schema.migrate(url, user, password)
    new Database(url, user, password)

object DatabaseConfig:
  val DefaultUser = "banking"
  val DefaultPassword = "banking"

object Schema:
  def migrate(url: String, user: String, password: String): Unit =
    Using.resource(DriverManager.getConnection(url, user, password)) { connection =>
      applyMigrations(connection)
    }

  private def applyMigrations(connection: Connection): Unit =
    connection.setAutoCommit(false)
    try
      apply(connection)
      connection.commit()
    catch
      case error: Exception =>
        connection.rollback()
        throw error
    finally
      connection.setAutoCommit(true)

  private def apply(connection: Connection): Unit =
    connection.createStatement().execute(
      """
      CREATE TABLE IF NOT EXISTS accounts (
        account_id VARCHAR(64) NOT NULL,
        opened_at TIMESTAMP NOT NULL,
        PRIMARY KEY (account_id)
      )
      """
    )
    connection.createStatement().execute(
      """
      CREATE TABLE IF NOT EXISTS ledger_transactions (
        transaction_id VARCHAR(36) NOT NULL,
        operation VARCHAR(32) NOT NULL,
        occurred_at TIMESTAMP NOT NULL,
        reverses_transaction_id VARCHAR(36),
        sequence_no BIGINT GENERATED BY DEFAULT AS IDENTITY,
        PRIMARY KEY (transaction_id),
        UNIQUE (reverses_transaction_id)
      )
      """
    )
    connection.createStatement().execute(
      """
      CREATE TABLE IF NOT EXISTS ledger_entries (
        transaction_id VARCHAR(36) NOT NULL,
        entry_index INT NOT NULL,
        account VARCHAR(64) NOT NULL,
        customer_account_id VARCHAR(64),
        direction VARCHAR(8) NOT NULL,
        amount NUMERIC(19,6) NOT NULL,
        currency VARCHAR(8) NOT NULL,
        PRIMARY KEY (transaction_id, entry_index),
        FOREIGN KEY (transaction_id) REFERENCES ledger_transactions (transaction_id) ON DELETE CASCADE
      )
      """
    )
    connection.createStatement().execute(
      """
      CREATE TABLE IF NOT EXISTS audit_log (
        audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        transaction_id VARCHAR(36) NOT NULL,
        operation VARCHAR(32) NOT NULL,
        account_id VARCHAR(64) NOT NULL,
        amount NUMERIC(19,6) NOT NULL,
        resulting_balance NUMERIC(19,6) NOT NULL,
        occurred_at TIMESTAMP NOT NULL,
        PRIMARY KEY (audit_id)
      )
      """
    )
    connection.createStatement().execute(
      """
      CREATE TABLE IF NOT EXISTS bill_payment_inquiries (
        inquiry_id VARCHAR(36) NOT NULL,
        account_id VARCHAR(64) NOT NULL,
        biller_code VARCHAR(64) NOT NULL,
        reference_code1 VARCHAR(128) NOT NULL,
        reference_code2 VARCHAR(128) NOT NULL,
        amount NUMERIC(19,6) NOT NULL,
        expires_at TIMESTAMP NOT NULL,
        status VARCHAR(16) NOT NULL,
        PRIMARY KEY (inquiry_id)
      )
      """
    )
    connection.createStatement().execute(
      """
      CREATE TABLE IF NOT EXISTS bill_payment_processes (
        payment_id VARCHAR(36) NOT NULL,
        inquiry_id VARCHAR(36) NOT NULL,
        account_id VARCHAR(64) NOT NULL,
        biller_code VARCHAR(64) NOT NULL,
        reference_code1 VARCHAR(128) NOT NULL,
        reference_code2 VARCHAR(128) NOT NULL,
        amount NUMERIC(19,6) NOT NULL,
        status VARCHAR(32) NOT NULL,
        resulting_balance NUMERIC(19,6),
        receipt_code VARCHAR(255),
        receipt_paid_at TIMESTAMP,
        failure_code VARCHAR(64),
        failure_message VARCHAR(512),
        created_at TIMESTAMP NOT NULL,
        updated_at TIMESTAMP NOT NULL,
        PRIMARY KEY (payment_id)
      )
      """
    )

final class Database(
    val url: String,
    val user: String = DatabaseConfig.DefaultUser,
    val password: String = DatabaseConfig.DefaultPassword
) extends AutoCloseable:
  val dataSource: HikariDataSource =
    val jdbcDataSource = new JdbcDataSource()
    jdbcDataSource.setURL(url)
    jdbcDataSource.setUser(user)
    jdbcDataSource.setPassword(password)

    val hikariDataSource = new HikariDataSource()
    hikariDataSource.setDataSource(jdbcDataSource)
    hikariDataSource.setMaximumPoolSize(10)
    hikariDataSource.setConnectionTimeout(5000)
    Using.resource(hikariDataSource.getConnection())(_ => ())
    hikariDataSource

  def withConnection[A](operation: Connection => A): A =
    Using.resource(dataSource.getConnection())(operation)

  def withTransaction[A](operation: Connection => A): A =
    val connection = dataSource.getConnection()
    connection.setAutoCommit(false)
    try
      val result = operation(connection)
      connection.commit()
      result
    catch
      case error: Exception =>
        connection.rollback()
        throw error
    finally
      connection.setAutoCommit(true)
      connection.close()

  override def close(): Unit = dataSource.close()
